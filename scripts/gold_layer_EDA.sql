---- Ranking Analysis
-- Ranking measure values by a dimension
--- Which 5 products generate the highest revenue
with revenue_per_product as(
select
  dp.product_number
  , dp.product_name
  , sum(fs2.sales_amount) as product_revenue
  , row_number() over (order by sum(fs2.sales_amount) desc) as rn
from gold.fact_sales fs2 
left join gold.dim_products dp 
  on fs2.product_key = dp.product_key
group by 1,2)
select 
  rpp.product_number
  , rpp.product_name
  , rpp.product_revenue
from revenue_per_product rpp
where
  rpp.rn <=5
;

--- Worst performing 5 products
with revenue_per_product as(
select
  dp.product_number
  , dp.product_name
  , sum(fs2.sales_amount) as product_revenue
  , row_number() over (order by sum(fs2.sales_amount) asc) as rn
from gold.fact_sales fs2 
left join gold.dim_products dp 
  on fs2.product_key = dp.product_key
group by 1,2)
select 
  rpp.product_number
  , rpp.product_name
  , rpp.product_revenue
from revenue_per_product rpp
where
  rpp.rn <=5
;

-- Find the top 10 customers who have generated the highest revenue
select *
from(select 
  dc.customer_key 
  , dc.first_name 
  , dc.last_name 
  , sum(fs2.sales_amount) as customer_revenue
  , rank() over (order by sum(fs2.sales_amount) desc) as customer_rank
from gold.fact_sales fs2 
left join gold.dim_customers dc 
  on fs2.customer_key = dc.customer_key
group by 1,2,3) t
where t.customer_rank <=10;

-- Find the 3 customers with the fewest orders placed
select *
from (select
  dc.customer_key 
  , dc.first_name 
  , dc.last_name 
  , count(distinct fs2.order_number) as orders_placed
  , row_number() over (order by count(distinct fs2.order_number) asc) customer_rank
from gold.fact_sales fs2 
left join gold.dim_customers dc 
  on fs2.customer_key = dc.customer_key 
group by 1,2,3) t
where t.customer_rank <=3;
