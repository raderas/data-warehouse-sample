-- Magnitude analysis

-- Find total customers by countries
select dc.country,
  count(dc.customer_key) as total_customers
from gold.dim_customers dc
group by 1
order by total_customers desc; 

-- Find total customers by gender
select 
  dc.gender,
  count(customer_key) as total_customers
from gold.dim_customers dc
group by 1
order by total_customers desc;

-- Find total products by category
SELECT
  dp.product_category as category_name
  , count(dp.product_key) AS total_products
FROM gold.dim_products dp
GROUP BY 1
order by total_products desc;

-- What is the average cost in each category?
select 
  dp.product_category as category_name
  , floor(avg(dp."cost"))::int as average_cost
from gold.dim_products dp
group by 1
order by average_cost desc;

-- What is the total revenue generated for each category?
select
  dp.product_category
  , sum(fs2.sales_amount) as total_revenue
from gold.dim_products dp
left join gold.fact_sales fs2 
  on dp.product_key = fs2.product_key 
group by 1
order by total_revenue desc 
;

-- Find total revenue generated by each customer
select
  dc.customer_key 
  , dc.first_name 
  , dc.last_name 
  , sum(fs2.sales_amount) as total_revenue
from gold.fact_sales fs2 
left join gold.dim_customers dc
  on fs2.customer_key = dc.customer_key 
group by 1,2,3
order by total_revenue desc

-- What is the distribution of sold items across countries?
